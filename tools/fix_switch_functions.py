"""Generate explicit function boundaries for functions whose jump tables XenonRecomp
reported as "trying to jump outside function".

Those functions have no .pdata entry (leaf functions), so XenonAnalyse's linear sweep
cuts them at the first bctr. We re-derive the real extent: start from the function
start the recompiler chose, then sweep forward following every forward branch and
every jump-table label until a terminator is reached past all of them.

Usage: python fix_switch_functions.py
  reads  notes/xenonrecomp.log, config/MCLA_switch_tables.toml, ppc/ppc_func_mapping.cpp
  writes the generated block in config/MCLA.toml (between the BEGIN/END markers)
"""
import bisect
import codecs
import os
import re
import struct
import sys
import tomllib

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "tools"))
from ppcimage import Image  # noqa: E402

BEGIN = "# BEGIN generated by tools/fix_switch_functions.py"
END = "# END generated by tools/fix_switch_functions.py"
BLR, BCTR = 0x4E800020, 0x4E800420


def branch_target(ins, pc):
    """Target of a non-linking relative b/bc, or None."""
    op = ins >> 26
    if ins & 1 or ins & 2:  # LK or AA
        return None
    if op == 18:
        d = ins & 0x03FFFFFC
        return pc + (d - 0x04000000 if d & 0x02000000 else d)
    if op == 16:
        d = ins & 0xFFFC
        return pc + (d - 0x10000 if d & 0x8000 else d)
    return None


def is_unconditional_end(ins):
    if ins in (BLR, BCTR):
        return True
    if ins >> 26 == 18 and not ins & 1:  # b (no link)
        return True
    if ins >> 26 == 16 and (ins >> 21) & 0x14 == 0x14 and not ins & 1:  # bc always
        return True
    return False


def main():
    img = Image(os.path.join(ROOT, "extracted", "default.pe"))
    with open(os.path.join(ROOT, "config", "MCLA_switch_tables.toml"), "rb") as f:
        switches = {s["base"]: s for s in tomllib.load(f)["switch"]}
    raw = open(os.path.join(ROOT, "notes", "xenonrecomp.log"), "rb").read()
    # recompile.ps1 redirects with Windows PowerShell, which writes UTF-16.
    log = raw.decode("utf-16" if raw[:2] in (codecs.BOM_UTF16_LE, codecs.BOM_UTF16_BE) else "utf-8", errors="replace")
    bad_sites = sorted({int(m, 16) for m in
                        re.findall(r"Switch case at ([0-9A-Fa-f]+) is trying to jump outside", log)})
    mapping = open(os.path.join(ROOT, "ppc", "ppc_func_mapping.cpp")).read()
    starts = sorted(int(a, 16) for a in re.findall(r"\{ 0x([0-9A-F]+), sub_", mapping))
    pdata_starts = [b for b, _ in img.functions]

    # Keep boundaries from earlier runs; this pass only adds/refines.
    cfg_path = os.path.join(ROOT, "config", "MCLA.toml")
    cfg = open(cfg_path).read()
    results = {}
    if BEGIN in cfg:
        old = cfg[cfg.index(BEGIN): cfg.index(END)]
        for a, s in re.findall(r"address = 0x([0-9A-F]+), size = 0x([0-9A-F]+)", old):
            results[int(a, 16)] = int(s, 16)
    previous = dict(results)

    table_bases = sorted(switches)
    for site in bad_sites:
        # The table applies to the first bctr after its base (the `lis` of the pattern).
        sw = switches[table_bases[bisect.bisect_right(table_bases, site) - 1]]
        lowest = min(sw["labels"] + [site])
        start = starts[bisect.bisect_right(starts, lowest) - 1]
        if start in results and start not in previous:
            continue
        # Hard limit: next .pdata function (those boundaries are authoritative).
        nxt = bisect.bisect_right(pdata_starts, site)
        limit = pdata_starts[nxt] if nxt < len(pdata_starts) else site + 0x10000
        furthest = start
        pc = start
        end = None
        while pc < limit:
            ins = img.u32(pc)
            if ins == 0 and pc >= furthest:
                end = pc  # padding
                break
            t = branch_target(ins, pc)
            if t is not None and pc < t < limit:
                furthest = max(furthest, t)
            if pc in switches:
                sw = switches[pc]
                for t in sw["labels"] + [sw.get("default", 0)]:
                    if pc < t < limit:
                        furthest = max(furthest, t)
            if is_unconditional_end(ins) and pc >= furthest:
                end = pc + 4
                break
            pc += 4
        if end is None:
            print(f"warning: sub_{start:08X} ran into limit 0x{limit:08X}; using it")
            end = limit
        results[start] = end - start
        # Drop earlier entries that this (larger) function now swallows.
        for other in [a for a in results if start < a < end]:
            del results[other]

    # Remove entries nested inside another explicit function.
    ordered = sorted(results.items())
    for i, (a, s) in enumerate(ordered):
        if any(b < a and a + s <= b + t for b, t in ordered[:i]):
            del results[a]

    lines = [BEGIN,
             f"# {len(results)} leaf functions containing jump tables (no .pdata entry)",
             "functions = ["]
    for start, size in sorted(results.items()):
        lines.append(f"    {{ address = 0x{start:08X}, size = 0x{size:X} }},")
    lines += ["]", END]
    block = "\n".join(lines)

    if BEGIN in cfg:
        cfg = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), lambda _: block, cfg, flags=re.S)
    else:
        cfg = cfg.rstrip() + "\n\n" + block + "\n"
    open(cfg_path, "w").write(cfg)
    print(f"{len(bad_sites)} failing switch sites -> {len(results)} explicit functions written")


if __name__ == "__main__":
    main()
