"""Find absolute jump tables XenonAnalyse missed and append them to
config/MCLA_switch_tables.toml (between generated-block markers).

A missed table makes the recompiler treat the switch's `bctr` as an indirect
call, which fails at runtime ("indirect call to X has no recompiled function").
XenonAnalyse needs a nearby `cmplwi`/`bgt` bounds check to size a table; these
tables are bounds-checked elsewhere, so the size is inferred from the table
contents instead: entries are code addresses inside the enclosing function, and
an inline table ends where its first case label begins.

Pattern (any order within the window, ending at bctr):
    lis   rA, hi ; addi rA, rA, lo      table = (hi << 16) + lo
    slwi  rI, rIdx, 2                   (rlwinm rI, rIdx, 2, 0, 29)
    lwzx  rD, rA, rI
    mtctr rD
    bctr

Usage: python find_jump_tables.py   (run after XenonAnalyse and XenonRecomp)
"""
import bisect
import os
import re
import struct
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "tools"))
from ppcimage import Image  # noqa: E402

TOML = os.path.join(ROOT, "config", "MCLA_switch_tables.toml")
BEGIN = "# BEGIN generated by tools/find_jump_tables.py"
END = "# END generated by tools/find_jump_tables.py"
BCTR = 0x4E800420


def sext16(v):
    return v - 0x10000 if v & 0x8000 else v


def main():
    img = Image(os.path.join(ROOT, "extracted", "default.pe"))
    text = open(TOML).read()
    if BEGIN in text:
        text = text[:text.index(BEGIN)].rstrip() + "\n"
    known = sorted(int(b, 16) for b in re.findall(r"base = 0x([0-9A-Fa-f]+)", text))
    mapping = open(os.path.join(ROOT, "ppc", "ppc_func_mapping.cpp")).read()
    starts = sorted(int(a, 16) for a in re.findall(r"\{ 0x([0-9A-F]+), ", mapping))
    pdata_starts = [b for b, _ in img.functions]

    found, unmatched = [], 0
    for _, va, size in img.code_ranges():
        off = va - img.base
        words = struct.unpack_from(f">{size // 4}I", img.data, off)
        for i, w in enumerate(words):
            if w != BCTR:
                continue
            bctr = va + i * 4
            # Already covered: a known table base within the preceding window.
            k = bisect.bisect_right(known, bctr) - 1
            if k >= 0 and bctr - known[k] <= 0x30:
                continue
            window = [(va + j * 4, words[j]) for j in range(max(0, i - 10), i)]
            mtctr = next(((a, x) for a, x in reversed(window) if (x & 0xFC1FFFFF) == 0x7C0903A6), None)
            if not mtctr:
                unmatched += 1
                continue
            rd = (mtctr[1] >> 21) & 31
            lwzx = next(((a, x) for a, x in reversed(window)
                         if a < mtctr[0] and x >> 26 == 31 and (x >> 1) & 0x3FF == 23 and (x >> 21) & 31 == rd), None)
            if not lwzx:
                unmatched += 1
                continue
            ra, rb = (lwzx[1] >> 16) & 31, (lwzx[1] >> 11) & 31
            base_reg = idx_reg = lis = addi = None
            for a, x in window:
                if a >= lwzx[0]:
                    break
                op = x >> 26
                if op == 15 and (x >> 16) & 31 == 0 and (x >> 21) & 31 in (ra, rb):
                    lis, base_reg = (a, x), (x >> 21) & 31
                elif op == 14 and base_reg is not None and (x >> 21) & 31 == base_reg and (x >> 16) & 31 == base_reg:
                    addi = (a, x)
                elif op == 21 and (x >> 11) & 31 == 2 and (x >> 6) & 31 == 0 and (x >> 1) & 31 == 29:
                    idx_reg = (x >> 21) & 31  # rlwinm rA(dest)=x>>16, rS(src)=x>>21
                    idx_dest = (x >> 16) & 31
            if not (lis and addi and idx_reg is not None):
                unmatched += 1
                continue
            table = ((lis[1] & 0xFFFF) << 16) + sext16(addi[1] & 0xFFFF) & 0xFFFFFFFF

            s = bisect.bisect_right(starts, bctr) - 1
            f_start = starts[s]
            f_end = starts[s + 1] if s + 1 < len(starts) else f_start + 0x10000
            if table == bctr + 4:
                # Inline table right after the bctr: the previous run's boundaries may
                # have split the function at the table (leaf functions have no .pdata),
                # so only the next .pdata function bounds the cases.
                p = bisect.bisect_right(pdata_starts, bctr)
                f_end = pdata_starts[p] if p < len(pdata_starts) else bctr + 0x10000
            labels = []
            limit = 0xFFFFFFFF
            while len(labels) < 512:
                addr = table + 4 * len(labels)
                if f_start <= addr < f_end and addr >= limit:
                    break  # inline table: reached the first case label
                try:
                    e = img.u32(addr)
                except struct.error:
                    break
                if e & 3 or not (f_start <= e < f_end):
                    break
                labels.append(e)
                limit = min(limit, e)
            if len(labels) < 2:
                unmatched += 1
                continue
            found.append((lis[0], idx_reg, labels))

    lines = [BEGIN, f"# {len(found)} absolute jump tables without a nearby bounds check"]
    for base, r, labels in sorted(found):
        lines += ["[[switch]]", f"base = 0x{base:08X}", f"r = {r}", "labels = ["]
        lines += [f"    0x{l:08X}," for l in labels] + ["]", ""]
    lines.append(END)
    open(TOML, "w", newline="\n").write(text + "\n" + "\n".join(lines) + "\n")
    print(f"{len(found)} missed jump tables added; {unmatched} other bctr sites (indirect calls/tail calls)")


if __name__ == "__main__":
    main()
