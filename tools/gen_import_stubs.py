"""Generate MCLA/kernel/generated_stubs.cpp: a logging stub for every kernel/XAM
import the recompiled code references (ppc/ppc_recomp_shared.h) that has no
GUEST_IMPORT(...) implementation under MCLA/.

Run after regenerating ppc/ or adding/removing implementations.
"""
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "MCLA", "kernel", "generated_stubs.cpp")


def main():
    shared = open(os.path.join(ROOT, "ppc", "ppc_recomp_shared.h")).read()
    referenced = sorted(set(re.findall(r"PPC_EXTERN_FUNC\(__imp__(\w+)\)", shared)) -
                        {n for n in re.findall(r"PPC_EXTERN_FUNC\(__imp__(\w+)\)", shared)
                         if n.startswith("sub_")})

    implemented = set()
    for dirpath, _, files in os.walk(os.path.join(ROOT, "MCLA")):
        for f in files:
            path = os.path.join(dirpath, f)
            if f.endswith(".cpp") and os.path.abspath(path) != OUT:
                implemented |= set(re.findall(r"GUEST_IMPORT\((\w+)\)", open(path).read()))

    missing = [n for n in referenced if n not in implemented]
    extra = sorted(implemented - set(referenced))
    lines = [
        "// Generated by tools/gen_import_stubs.py - do not edit.",
        "// Imports referenced by the game that have no implementation yet. Each logs",
        "// its first calls and returns 0.",
        '#include "imports.h"',
        "",
        "#include <mutex>",
        "#include <unordered_map>",
        "",
        "static void Unimplemented(const char* name, PPCContext& ctx)",
        "{",
        "    static std::mutex lock;",
        "    static std::unordered_map<const char*, int> calls;",
        "    NoteImportCall(name);",
        "    int n;",
        "    {",
        "        std::lock_guard guard(lock);",
        "        n = ++calls[name];",
        "    }",
        "    if (n <= 4 || (n & (n - 1)) == 0)",
        '        LOGI("UNIMPLEMENTED %s(%08X, %08X, %08X, %08X) lr=%08X [call %d]", name,',
        "             ctx.r3.u32, ctx.r4.u32, ctx.r5.u32, ctx.r6.u32, uint32_t(ctx.lr), n);",
        "    ctx.r3.u64 = 0;",
        "}",
        "",
    ]
    for n in missing:
        lines.append(f'GUEST_IMPORT({n}) {{ Unimplemented("{n}", ctx); }}')
    open(OUT, "w", newline="\n").write("\n".join(lines) + "\n")
    print(f"{len(referenced)} imports referenced, {len(referenced) - len(missing)} implemented, "
          f"{len(missing)} stubbed -> {os.path.relpath(OUT, ROOT)}")
    if extra:
        print("implemented but not referenced (check spelling):", ", ".join(extra))


if __name__ == "__main__":
    main()
