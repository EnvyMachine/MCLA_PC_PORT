"""Enable/disable entry tracing of every recompiled function in an address range
(default: the statically linked D3D/XGraphics library), for identifying D3D API
functions by behaviour.

  python gen_d3d_trace.py enable [lo hi]   -> hooks in config/MCLA.toml + generated C++
  python gen_d3d_trace.py disable          -> removes them

Each traced function gets a mid-asm hook at its first instruction that calls
D3DTraceRecord(index, ctx) (MCLA/debug/d3d_trace.cpp). Run tools/recompile.ps1 and
rebuild afterwards; run the game with MCLA_D3D_TRACE=<seconds> to write
notes/d3d_trace.txt.
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CONFIG = os.path.join(ROOT, "config", "MCLA.toml")
GENERATED = os.path.join(ROOT, "MCLA", "debug", "d3d_trace_hooks.generated.cpp")
BEGIN = "# BEGIN generated by tools/gen_d3d_trace.py"
END = "# END generated by tools/gen_d3d_trace.py"


def main():
    mode = sys.argv[1] if len(sys.argv) > 1 else "enable"
    lo = int(sys.argv[2], 16) if len(sys.argv) > 3 else 0x823FA000
    hi = int(sys.argv[3], 16) if len(sys.argv) > 3 else 0x82470000

    functions = []
    if mode == "enable":
        mapping = open(os.path.join(ROOT, "ppc", "ppc_func_mapping.cpp")).read()
        functions = sorted(a for a in (int(x, 16) for x in re.findall(r"\{ 0x([0-9A-F]+), ", mapping)) if lo <= a < hi)

    cfg = open(CONFIG).read()
    if BEGIN in cfg:
        cfg = cfg[:cfg.index(BEGIN)].rstrip() + "\n" + cfg[cfg.index(END) + len(END):].lstrip("\n")
    if functions:
        block = [BEGIN, f"# entry tracing of {len(functions)} functions in {lo:08X}-{hi:08X}"]
        for a in functions:
            block += ["[[midasm_hook]]", f'name = "D3DTrace_{a:08X}"', f"address = 0x{a:08X}",
                      'registers = ["ctx"]', ""]
        block.append(END)
        cfg = cfg.rstrip() + "\n\n" + "\n".join(block) + "\n"
    open(CONFIG, "w", newline="\n").write(cfg)

    lines = [
        "// Generated by tools/gen_d3d_trace.py - do not edit.",
        '#include "../runtime/guest.h"',
        "",
        "void D3DTraceRecord(uint32_t index, PPCContext& ctx);",
        f"extern const uint32_t kD3DTracedFunctions[] = {{ {', '.join(f'0x{a:08X}' for a in functions) or '0'} }};",
        f"extern const uint32_t kD3DTracedFunctionCount = {len(functions)};",
        "",
    ]
    for i, a in enumerate(functions):
        lines.append(f"void D3DTrace_{a:08X}(PPCContext& ctx) {{ D3DTraceRecord({i}, ctx); }}")
    os.makedirs(os.path.dirname(GENERATED), exist_ok=True)
    open(GENERATED, "w", newline="\n").write("\n".join(lines) + "\n")
    print(f"{mode}: {len(functions)} traced functions")


if __name__ == "__main__":
    main()
